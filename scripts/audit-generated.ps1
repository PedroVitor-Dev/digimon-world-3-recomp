param([Parameter(Mandatory=$true)][string]$SourcePath)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$source = Get-Content -LiteralPath $SourcePath -Raw
$invalidCount = [regex]::Matches($source, '// INVALID:').Count
$implicitStubCount = [regex]::Matches($source, 'STUB generated by JAL').Count
Write-Output "Invalid instruction markers: $invalidCount"
Write-Output "Implicit empty JAL stubs: $implicitStubCount"
if ($invalidCount -gt 0 -or $implicitStubCount -gt 0) {
    throw 'Generated source rejected. Review code/data boundaries and unresolved calls before building a game runtime.'
}
Write-Output 'Basic marker audit passed. This does not prove instruction correctness, function coverage or game compatibility.'
